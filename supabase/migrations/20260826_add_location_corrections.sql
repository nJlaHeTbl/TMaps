create table if not exists public.place_location_corrections (
  id bigint generated by default as identity primary key,
  place_key text not null check (char_length(place_key) between 3 and 120),
  current_lat double precision not null check (current_lat between 40.45 and 55.55),
  current_lng double precision not null check (current_lng between 46.45 and 87.40),
  proposed_lat double precision not null check (proposed_lat between 40.45 and 55.55),
  proposed_lng double precision not null check (proposed_lng between 46.45 and 87.40),
  username text not null check (char_length(trim(username)) between 2 and 30),
  comment text check (comment is null or char_length(comment) <= 300),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

create index if not exists place_location_corrections_status_created_at_idx
  on public.place_location_corrections (status, created_at desc);

create table if not exists public.place_location_overrides (
  place_key text primary key check (char_length(place_key) between 3 and 120),
  lat double precision not null check (lat between 40.45 and 55.55),
  lng double precision not null check (lng between 46.45 and 87.40),
  location_correction_id bigint
    references public.place_location_corrections(id),
  updated_at timestamptz not null default now()
);

alter table public.place_location_corrections enable row level security;
alter table public.place_location_overrides enable row level security;

revoke all on public.place_location_corrections from anon, authenticated;
revoke all on public.place_location_overrides from anon, authenticated;

drop policy if exists "Public location overrides are readable"
  on public.place_location_overrides;
create policy "Public location overrides are readable"
  on public.place_location_overrides for select
  to anon, authenticated
  using (true);

grant select on public.place_location_overrides to anon, authenticated;

create or replace function public.submit_place_location_correction(
  p_place_key text,
  p_current_lat double precision,
  p_current_lng double precision,
  p_proposed_lat double precision,
  p_proposed_lng double precision,
  p_username text,
  p_comment text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  correction_id bigint;
begin
  if p_current_lat not between 40.45 and 55.55
     or p_proposed_lat not between 40.45 and 55.55
     or p_current_lng not between 46.45 and 87.40
     or p_proposed_lng not between 46.45 and 87.40 then
    raise exception 'Обе точки должны находиться в Казахстане';
  end if;

  if char_length(trim(p_place_key)) not between 3 and 120 then
    raise exception 'Неизвестная точка';
  end if;

  if char_length(trim(p_username)) not between 2 and 30 then
    raise exception 'Имя должно содержать от 2 до 30 символов';
  end if;

  if p_comment is not null and char_length(trim(p_comment)) > 300 then
    raise exception 'Комментарий слишком длинный';
  end if;

  if abs(p_current_lat - p_proposed_lat) < 0.000001
     and abs(p_current_lng - p_proposed_lng) < 0.000001 then
    raise exception 'Передвинь метку в новое место';
  end if;

  insert into public.place_location_corrections (
    place_key,
    current_lat,
    current_lng,
    proposed_lat,
    proposed_lng,
    username,
    comment
  ) values (
    trim(p_place_key),
    p_current_lat,
    p_current_lng,
    p_proposed_lat,
    p_proposed_lng,
    trim(p_username),
    nullif(trim(p_comment), '')
  )
  returning id into correction_id;

  return correction_id;
end;
$$;

revoke all on function public.submit_place_location_correction(
  text,
  double precision,
  double precision,
  double precision,
  double precision,
  text,
  text
) from public;

grant execute on function public.submit_place_location_correction(
  text,
  double precision,
  double precision,
  double precision,
  double precision,
  text,
  text
) to anon, authenticated;

create or replace function public.publish_approved_location_correction()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.status = 'approved' and old.status <> 'approved' then
    insert into public.place_location_overrides (
      place_key,
      lat,
      lng,
      location_correction_id,
      updated_at
    ) values (
      new.place_key,
      new.proposed_lat,
      new.proposed_lng,
      new.id,
      now()
    )
    on conflict (place_key) do update set
      lat = excluded.lat,
      lng = excluded.lng,
      location_correction_id = excluded.location_correction_id,
      updated_at = excluded.updated_at;
    new.reviewed_at = now();
  elsif new.status = 'rejected' and old.status <> 'rejected' then
    new.reviewed_at = now();
  end if;

  return new;
end;
$$;

drop trigger if exists publish_approved_location_correction
  on public.place_location_corrections;
create trigger publish_approved_location_correction
before update of status on public.place_location_corrections
for each row
execute function public.publish_approved_location_correction();
