create table if not exists public.pedestrian_alerts (
  id bigint generated by default as identity primary key,
  lat double precision not null check (lat between 40.5 and 55.5),
  lng double precision not null check (lng between 46 and 88),
  alert_type text not null check (
    alert_type in (
      'open',
      'closed',
      'ice',
      'construction',
      'snow',
      'flooding',
      'obstacle'
    )
  ),
  username text not null check (char_length(username) between 2 and 30),
  description text check (description is null or char_length(description) <= 240),
  reporter_key text not null check (char_length(reporter_key) between 12 and 80),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create index if not exists pedestrian_alerts_expires_at_idx
  on public.pedestrian_alerts (expires_at desc);

create index if not exists pedestrian_alerts_position_idx
  on public.pedestrian_alerts (lat, lng, created_at desc);

alter table public.pedestrian_alerts enable row level security;
revoke all on public.pedestrian_alerts from anon, authenticated;
revoke all on sequence public.pedestrian_alerts_id_seq from anon, authenticated;

create or replace function public.get_active_pedestrian_alerts()
returns table (
  id bigint,
  lat double precision,
  lng double precision,
  alert_type text,
  username text,
  description text,
  created_at timestamptz,
  expires_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    alert.id,
    alert.lat,
    alert.lng,
    alert.alert_type,
    alert.username,
    alert.description,
    alert.created_at,
    alert.expires_at
  from public.pedestrian_alerts as alert
  where alert.expires_at > now()
  order by alert.created_at desc
  limit 1000;
$$;

revoke all on function public.get_active_pedestrian_alerts() from public;
grant execute on function public.get_active_pedestrian_alerts()
  to anon, authenticated;

create or replace function public.report_pedestrian_alert(
  p_lat double precision,
  p_lng double precision,
  p_alert_type text,
  p_username text,
  p_reporter_key text,
  p_description text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  alert_id bigint;
  alert_duration interval;
  clean_description text;
begin
  if p_lat not between 40.5 and 55.5
     or p_lng not between 46 and 88 then
    raise exception 'Точка должна находиться в Казахстане';
  end if;

  if p_alert_type not in (
    'open',
    'closed',
    'ice',
    'construction',
    'snow',
    'flooding',
    'obstacle'
  ) then
    raise exception 'Неизвестный тип предупреждения';
  end if;

  if p_username is null
     or char_length(trim(p_username)) not between 2 and 30 then
    raise exception 'Некорректное имя';
  end if;

  if p_reporter_key is null
     or char_length(p_reporter_key) not between 12 and 80 then
    raise exception 'Некорректный ключ устройства';
  end if;

  clean_description := nullif(trim(p_description), '');
  if clean_description is not null and char_length(clean_description) > 240 then
    raise exception 'Комментарий слишком длинный';
  end if;

  if (
    select count(*)
    from public.pedestrian_alerts as recent
    where recent.reporter_key = p_reporter_key
      and recent.created_at > now() - interval '1 hour'
  ) >= 6 then
    raise exception 'Слишком много сообщений. Попробуйте позже';
  end if;

  alert_duration := case p_alert_type
    when 'open' then interval '6 hours'
    when 'construction' then interval '3 days'
    when 'closed' then interval '24 hours'
    else interval '12 hours'
  end;

  if p_alert_type = 'open' then
    update public.pedestrian_alerts as previous
    set expires_at = now()
    where previous.expires_at > now()
      and previous.alert_type <> 'open'
      and abs(previous.lat - p_lat) <= 0.0007
      and abs(previous.lng - p_lng) <= 0.0009;
  end if;

  select existing.id
  into alert_id
  from public.pedestrian_alerts as existing
  where existing.reporter_key = p_reporter_key
    and existing.alert_type = p_alert_type
    and existing.expires_at > now()
    and abs(existing.lat - p_lat) <= 0.00035
    and abs(existing.lng - p_lng) <= 0.00045
  order by existing.created_at desc
  limit 1;

  if alert_id is not null then
    update public.pedestrian_alerts as existing
    set
      lat = p_lat,
      lng = p_lng,
      username = trim(p_username),
      description = clean_description,
      created_at = now(),
      expires_at = now() + alert_duration
    where existing.id = alert_id;
    return alert_id;
  end if;

  insert into public.pedestrian_alerts (
    lat,
    lng,
    alert_type,
    username,
    description,
    reporter_key,
    expires_at
  ) values (
    p_lat,
    p_lng,
    p_alert_type,
    trim(p_username),
    clean_description,
    p_reporter_key,
    now() + alert_duration
  )
  returning id into alert_id;

  return alert_id;
end;
$$;

revoke all on function public.report_pedestrian_alert(
  double precision,
  double precision,
  text,
  text,
  text,
  text
) from public;
grant execute on function public.report_pedestrian_alert(
  double precision,
  double precision,
  text,
  text,
  text,
  text
) to anon, authenticated;

