"""Build a D1 import SQL file from a Supabase JSON export.

Usage: python -I backend/scripts/build_supabase_import.py <export_prefix> <out.sql>
Example prefix: backend/data/supabase-2026-11-25-

Keeps the Supabase ids, because the app builds place keys such as
`community:<id>` from them. Raw votes are not readable with the public key,
so each counted vote becomes one row with a generated `import-...` voter key.
"""
import datetime
import hashlib
import json
import pathlib
import sys

prefix, out_path = sys.argv[1], pathlib.Path(sys.argv[2])


def load(name):
    return json.loads(pathlib.Path(prefix + name + '.json').read_text(encoding='utf-8'))


def sql(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return '1' if value else '0'
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def ts(value):
    moment = datetime.datetime.fromisoformat(str(value).replace('Z', '+00:00'))
    if moment.tzinfo is not None:
        moment = moment.astimezone(datetime.timezone.utc).replace(tzinfo=None)
    return moment.strftime('%Y-%m-%d %H:%M:%S')


def insert(table, columns, rows):
    lines = []
    for row in rows:
        values = ', '.join(sql(row[column]) for column in columns)
        lines.append(f'INSERT INTO {table} ({", ".join(columns)}) VALUES ({values});')
    return lines


toilet_columns = [
    'id', 'lat', 'lng', 'username', 'name', 'is_free', 'cleanliness', 'condition',
    'comment', 'place_kind', 'has_toilet', 'has_paper', 'has_soap',
    'wheelchair_accessible', 'phone_charging', 'access_type', 'created_at',
]
toilets = []
for row in load('toilets'):
    row = dict(row)
    # D1 requires is_free; the app hides this field for non-toilet kinds and
    # treats them as free, so a missing value is stored as 1.
    row['is_free'] = True if row.get('is_free') is None else row['is_free']
    row['created_at'] = ts(row['created_at'])
    toilets.append(row)

report_columns = [
    'id', 'place_key', 'lat', 'lng', 'username', 'cleanliness', 'condition',
    'has_toilet', 'has_paper', 'has_soap', 'wheelchair_accessible',
    'phone_charging', 'access_type', 'comment', 'created_at',
]
reports = []
for row in load('toilet_reports'):
    row = dict(row)
    row['created_at'] = ts(row['created_at'])
    reports.append(row)

votes = []
for total in load('place_vote_totals'):
    digest = hashlib.sha1(total['place_key'].encode('utf-8')).hexdigest()[:12]
    for kind, count, is_current in (('l', total['likes'], True), ('d', total['dislikes'], False)):
        for index in range(int(count)):
            votes.append({
                'place_key': total['place_key'],
                'voter_key': f'import-20261125-{digest}-{kind}{index + 1}',
                'is_current': is_current,
            })

lines = ['-- Generated by backend/scripts/build_supabase_import.py']
lines += insert('toilets', toilet_columns, toilets)
lines += insert('toilet_reports', report_columns, reports)
lines += insert('place_votes', ['place_key', 'voter_key', 'is_current'], votes)
out_path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(json.dumps({'toilets': len(toilets), 'toilet_reports': len(reports), 'place_votes': len(votes)}))
